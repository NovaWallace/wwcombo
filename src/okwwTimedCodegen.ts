import type { OkwwCharacter, OkwwProbe, OkwwProject } from './okwwExport';
import type { OkwwReplayCheckpoint, OkwwReplayPlan } from './okwwReplay';

const GENERATOR_REVISION = 'timed-v5-branches';

function py(value: string | number | unknown[]): string { return JSON.stringify(value); }

function signatureFor(project: OkwwProject, plan: OkwwReplayPlan): string {
  let hash = 2166136261;
  const routeConfig = JSON.stringify({
    rules: project.rules.map((rule) => [rule.stepId, rule.probe, rule.behavior, rule.onTimeout, rule.failureTargetStepId ?? '']),
    postChecks: (project.postChecks ?? []).map((check) => [check.stepId, check.probe, check.onFailure, check.failureTargetStepId ?? '']),
    replaySettings: project.replaySettings ?? {}
  });
  for (const event of [{ atMs: 0, type: GENERATOR_REVISION, code: routeConfig }, ...plan.events]) {
    for (const char of `${event.atMs}:${event.type}:${event.code};`) {
      hash = Math.imul(hash ^ char.charCodeAt(0), 16777619);
    }
  }
  return `${project.sourceChartId}:${(hash >>> 0).toString(16)}`;
}

export function renderTimedOkwwCharacter(character: OkwwCharacter, project: OkwwProject, plan: OkwwReplayPlan, checkpoints: OkwwReplayCheckpoint[], probes: OkwwProbe[]): string {
  const rank = (kind: string) => kind.endsWith('up') ? 0 : kind === 'post' ? 1 : kind === 'pre' ? 2 : 3;
  const events = [
    ...plan.events.map((event) => [event.atMs, event.type, event.code] as Array<string | number>),
    ...checkpoints.map((check) => [check.atMs, check.when, check.probe, check.slot, check.behavior,
      check.timeoutMs, check.failure, check.whileWaiting, check.inputCode, check.endMs, check.nextSwitchMs,
      check.maxRetries, check.failureTargetMs] as Array<string | number>)
  ].sort((a, b) => Number(a[0]) - Number(b[0]) || rank(String(a[1])) - rank(String(b[1])));
  const signature = signatureFor(project, plan);
  const startDelayMs = Math.max(0, Math.min(30_000, Math.round(project.replaySettings?.startDelayMs ?? 0)));
  const firstStep = [...project.chart.steps].filter((step) => !step.free && !['start_challenge', 'stop_recording'].includes(step.moveId))
    .sort((a, b) => a.startMin - b.startMin)[0];
  const startingSlot = firstStep && !firstStep.moveId.startsWith('switch_') ? firstStep.characterSlot ?? 1 : 0;
  const roster = ([1, 2, 3] as const).map((slot) => project.classes[slot]);
  const switchRetries = project.replaySettings?.switchFailure === 'retry'
    ? Math.max(1, Math.min(3, Math.round(project.replaySettings.switchMaxRetries ?? 1))) : 0;
  const switchVerifyTimeout = Math.max(300, Math.min(5000, Math.round(project.replaySettings?.switchVerifyTimeoutMs ?? 1500))) / 1000;
  const lines = [
    'import time',
    `from src.char.${character.className} import ${character.className} as _BuiltinCharacter`,
    '',
    `class ${character.className}(_BuiltinCharacter):`,
    `    _wwcombo_events = ${py(events)}`,
    `    _wwcombo_loop_start_ms = ${Math.round(plan.loopStartMs)}`,
    `    _wwcombo_total_ms = ${Math.round(plan.totalMs)}`,
    '',
    '    def _wwcombo_key(self, code):',
    '        key_config = self.task.key_config',
    '        keys = {',
    '            "KeyE": self.get_resonance_key(),',
    '            "KeyQ": self.get_echo_key(),',
    '            "KeyR": self.get_liberation_key(),',
    '            "KeyT": key_config.get("Tool Key", "t"),',
    '            "ShiftLeft": key_config.get("Dodge Key", "shift"),',
    '            "Space": key_config.get("Jump Key", "space"),',
    '            "Digit1": "1", "Digit2": "2", "Digit3": "3", "KeyF": "f",',
    '        }',
    '        return keys.get(code)',
    '',
    '    def _wwcombo_validate_start(self):',
    '        task = self.task',
    `        expected = ${py(roster)}`,
    '        actual = [type(char).__name__ if char is not None else None for char in task.chars]',
    '        if actual != expected:',
    '            task.raise_not_in_combat(f"wwcombo team slots mismatch: expected {expected}, got {actual}")',
    '        task.next_frame()',
    '        in_team, current_index, _ = task.in_team()',
    '        if not in_team:',
    '            task.raise_not_in_combat("wwcombo: cannot see team at replay start")',
    `        if ${startingSlot} and current_index != ${startingSlot - 1}:`,
    `            task.raise_not_in_combat("wwcombo: start with slot ${startingSlot} active")`,
    '',
    '    def _wwcombo_probe(self, actor, name):',
    '        if actor is None:',
    '            return False',
    '        if name == "liberation_cast":',
    '            return not actor.liberation_available()',
    ...probes.filter((probe) => checkpoints.some((check) => check.probe === probe.id) && probe.id !== 'liberation_cast')
      .flatMap((probe) => [
        `        if name == ${py(probe.id)}:`,
        `            return bool(${probe.expression.replace(/\bself\b/g, 'actor')})`
      ]),
    '        return False',
    '',
    '    def _wwcombo_emit(self, kind, code, held):',
    '        task = self.task',
    '        pressed = kind in ("keydown", "mousedown")',
    '        if pressed and code in held:',
    '            self._wwcombo_emit("mouseup" if code.startswith("Mouse") else "keyup", code, held)',
    '        if not pressed and code not in held:',
    '            return',
    '        if pressed:',
    '            held.add(code)',
    '        if code == "MouseLeft":',
    '            task.mouse_down() if pressed else task.mouse_up()',
    '        elif code == "MouseRight":',
    '            task.mouse_down(key="right") if pressed else task.mouse_up(key="right")',
    '        else:',
    '            key = self._wwcombo_key(code)',
    '            if key is None:',
    '                raise ValueError("unsupported wwcombo replay key: " + code)',
    '            task.send_key_down(key) if pressed else task.send_key_up(key)',
    '        if not pressed:',
    '            held.discard(code)',
    '',
    '    def _wwcombo_wait_until(self, deadline):',
    '        while True:',
    '            remaining = deadline - time.perf_counter()',
    '            if remaining <= 0:',
    '                return',
    '            if remaining > 0.06:',
    '                self.task.sleep(min(0.04, remaining - 0.02))',
    '            else:',
    '                time.sleep(min(remaining, 0.005))',
    '',
    '    def _wwcombo_verify_switch(self, target_slot, switched_at, held):',
    '        task = self.task',
    '        started = time.perf_counter()',
    `        settle_until = max(started, switched_at + ${switchVerifyTimeout})`,
    `        for attempt in range(${switchRetries + 1}):`,
    '            while True:',
    '                task.next_frame()',
    '                in_team, current_index, _ = task.in_team()',
    '                if in_team and current_index == target_slot - 1:',
    '                    for char in task.chars:',
    '                        if char is not None:',
    '                            char.is_current_char = char.index == current_index',
    '                    return time.perf_counter() - started',
    '                remaining = settle_until - time.perf_counter()',
    '                if remaining <= 0:',
    '                    break',
    '                task.sleep(min(0.05, remaining))',
    `            if attempt < ${switchRetries}:`,
    '                self.logger.warning(f"wwcombo switch to slot {target_slot} missed; retry {attempt + 1}")',
    '                code = "Digit" + str(target_slot)',
    '                self._wwcombo_emit("keydown", code, held)',
    '                try:',
    '                    self._wwcombo_wait_until(time.perf_counter() + 0.05)',
    '                finally:',
    '                    if code in held:',
    '                        self._wwcombo_emit("keyup", code, held)',
    `                settle_until = time.perf_counter() + ${switchVerifyTimeout}`,
    '        task.raise_not_in_combat("wwcombo: scheduled switch did not reach slot " + str(target_slot))',
    '',
    '    def _wwcombo_checkpoint(self, event, held):',
    '        at_ms, when, name, slot, behavior, timeout_ms, failure, while_waiting, input_code, end_ms, next_switch_ms, max_retries, failure_target_ms = event',
    '        task = self.task',
    '        actor = task.chars[slot - 1] if 0 < slot <= len(task.chars) else None',
    '        started = time.perf_counter()',
    '        task.next_frame()',
    '        ready = False',
    '        attempts = max_retries if when == "pre" and input_code.startswith("Digit") and behavior == "wait" else 1',
    '        for _ in range(attempts):',
    '            if behavior == "wait":',
    '                action = actor.click_with_interval if actor is not None and while_waiting == "basic_attack" else None',
    '                ready = bool(task.wait_until(lambda: self._wwcombo_probe(actor, name), time_out=timeout_ms / 1000.0, post_action=action, raise_if_not_found=False))',
    '            else:',
    '                ready = self._wwcombo_probe(actor, name)',
    '            if ready:',
    '                break',
    '        if ready:',
    '            return time.perf_counter() - started, None, None, None',
    '        self.logger.warning(f"wwcombo check failed: {name} at {at_ms}ms")',
    '        if failure == "continue" or (failure == "switch" and input_code.startswith("Digit")):',
    '            return time.perf_counter() - started, None, None, None',
    '        if failure == "abort":',
    '            task.raise_not_in_combat("wwcombo check failed: " + name)',
    '        if failure == "skip":',
    '            return time.perf_counter() - started, (input_code, at_ms, end_ms), None, None',
    '        if failure in ("switch", "next_run"):',
    '            return time.perf_counter() - started, None, next_switch_ms, None',
    '        if failure == "branch":',
    '            if failure_target_ms < 0 or failure_target_ms <= at_ms:',
    '                task.raise_not_in_combat("wwcombo branch has no valid forward target: " + name)',
    '            return time.perf_counter() - started, None, None, failure_target_ms',
    '        if failure == "retry":',
    '            duration = min(0.25, max(0.02, (end_ms - at_ms) / 1000.0))',
    '            for _ in range(2):',
    '                down = "mousedown" if input_code.startswith("Mouse") else "keydown"',
    '                up = "mouseup" if input_code.startswith("Mouse") else "keyup"',
    '                self._wwcombo_emit(down, input_code, held)',
    '                self._wwcombo_wait_until(time.perf_counter() + duration)',
    '                self._wwcombo_emit(up, input_code, held)',
    '                task.next_frame()',
    '                if task.wait_until(lambda: self._wwcombo_probe(actor, name), time_out=timeout_ms / 1000.0, raise_if_not_found=False):',
    '                    return time.perf_counter() - started, None, None, None',
    '            task.raise_not_in_combat("wwcombo outcome retry failed: " + name)',
    '        return time.perf_counter() - started, None, None, None',
    '',
    '    def do_perform(self):',
    '        task = self.task',
    `        signature = ${py(signature)}`,
    '        if (getattr(task, "_wwcombo_timed_signature", None) != signature or',
    '                getattr(task, "_wwcombo_timed_combat_start", None) != task.combat_start):',
    '            task._wwcombo_timed_signature = signature',
    '            task._wwcombo_timed_combat_start = task.combat_start',
    '            task._wwcombo_timed_startup_done = False',
    '            task._wwcombo_timed_next_start = None',
    '            task._wwcombo_timed_cursor = 0',
    '            task._wwcombo_timed_base = None',
    '            task._wwcombo_timed_pending_switch = None',
    '            task._wwcombo_timed_skipped_windows = []',
    '            task._wwcombo_timed_skip_until_ms = -1',
    '            task._wwcombo_timed_aborted = False',
    '            task._wwcombo_timed_last_late_log = -1e9',
    `            self.logger.warning(${py(`wwcombo replay ${GENERATOR_REVISION}: starting new combat run`)})`,
    '        if task._wwcombo_timed_aborted:',
    '            task.raise_not_in_combat("wwcombo replay interrupted; restart combat to reset")',
    '        if getattr(task, "_wwcombo_timed_running", False):',
    '            return',
    '        first_run = not task._wwcombo_timed_startup_done',
    '        origin_ms = 0 if first_run else self._wwcombo_loop_start_ms',
    '        events = self._wwcombo_events if first_run else [event for event in self._wwcombo_events if event[0] >= origin_ms]',
    '        if not events:',
    '            return',
    '        task._wwcombo_timed_running = True',
    '        held = set()',
    '        pending_switch = task._wwcombo_timed_pending_switch',
    '        skipped_windows = task._wwcombo_timed_skipped_windows',
    '        skip_until_ms = task._wwcombo_timed_skip_until_ms',
    `        start = task._wwcombo_timed_base if task._wwcombo_timed_base is not None else ((time.perf_counter() + ${startDelayMs / 1000}) if first_run else (task._wwcombo_timed_next_start or time.perf_counter()))`,
    '        task._wwcombo_timed_base = start',
    '        invocation_start = time.perf_counter()',
    '        try:',
    '            if first_run and task._wwcombo_timed_cursor == 0:',
    '                self._wwcombo_validate_start()',
    '            for cursor in range(task._wwcombo_timed_cursor, len(events)):',
    '                event = events[cursor]',
    '                at_ms, kind, code = event[:3]',
    '                deadline = start + (at_ms - origin_ms) / 1000.0',
    '                if not held and (time.perf_counter() - invocation_start >= 5.0 or deadline - invocation_start > 5.0):',
    '                    if time.perf_counter() - invocation_start < 5.0:',
    '                        self._wwcombo_wait_until(invocation_start + 5.0)',
    '                    task._wwcombo_timed_cursor = cursor',
    '                    task._wwcombo_timed_base = start',
    '                    task._wwcombo_timed_pending_switch = pending_switch',
    '                    task._wwcombo_timed_skipped_windows = skipped_windows',
    '                    task._wwcombo_timed_skip_until_ms = skip_until_ms',
    '                    return',
    '                task._wwcombo_timed_cursor = cursor + 1',
    '                if at_ms < skip_until_ms:',
    '                    continue',
    '                if pending_switch:',
    '                    self._wwcombo_wait_until(deadline)',
    '                    start += self._wwcombo_verify_switch(pending_switch[0], pending_switch[1], held)',
    '                    pending_switch = None',
    '                    deadline = start + (at_ms - origin_ms) / 1000.0',
    '                self._wwcombo_wait_until(deadline)',
    '                now = time.perf_counter()',
    '                late = now - deadline',
    '                if late > 0.02:',
    '                    if now - task._wwcombo_timed_last_late_log > 2.0:',
    '                        self.logger.warning(f"wwcombo input late by {late:.3f}s: {code}; shifting replay clock")',
    '                        task._wwcombo_timed_last_late_log = now',
    '                    start += late',
    '                if kind in ("pre", "post"):',
    '                    spent, skipped, next_run, branch_to = self._wwcombo_checkpoint(event, held)',
    '                    start += spent',
    '                    if skipped:',
    '                        skipped_windows.append(skipped)',
    '                        if skipped[0] in held:',
    '                            self._wwcombo_emit("mouseup" if skipped[0].startswith("Mouse") else "keyup", skipped[0], held)',
    '                    if next_run is not None:',
    '                        for held_code in tuple(held):',
    '                            self._wwcombo_emit("mouseup" if held_code.startswith("Mouse") else "keyup", held_code, held)',
    '                        skip_until_ms = next_run',
    '                    if branch_to is not None:',
    '                        for held_code in tuple(held):',
    '                            self._wwcombo_emit("mouseup" if held_code.startswith("Mouse") else "keyup", held_code, held)',
    '                        pending_switch = None',
    '                        skip_until_ms = branch_to',
    '                    continue',
    '                if any(code == window[0] and window[1] <= at_ms and (at_ms < window[2] or (at_ms == window[2] and kind.endswith("up"))) for window in skipped_windows):',
    '                    continue',
    '                self._wwcombo_emit(kind, code, held)',
    '                if kind == "keyup" and code in ("Digit1", "Digit2", "Digit3"):',
    '                    pending_switch = (int(code[-1]), time.perf_counter())',
    '            end_deadline = start + (self._wwcombo_total_ms - origin_ms) / 1000.0',
    '            if not held and end_deadline - invocation_start > 5.0:',
    '                self._wwcombo_wait_until(invocation_start + 5.0)',
    '                task._wwcombo_timed_cursor = len(events)',
    '                task._wwcombo_timed_base = start',
    '                task._wwcombo_timed_pending_switch = pending_switch',
    '                task._wwcombo_timed_skipped_windows = skipped_windows',
    '                task._wwcombo_timed_skip_until_ms = skip_until_ms',
    '                return',
    '            self._wwcombo_wait_until(end_deadline)',
    '            if pending_switch:',
    '                start += self._wwcombo_verify_switch(pending_switch[0], pending_switch[1], held)',
    '                end_deadline = start + (self._wwcombo_total_ms - origin_ms) / 1000.0',
    '            task._wwcombo_timed_next_start = start + (self._wwcombo_total_ms - origin_ms) / 1000.0',
    '            task._wwcombo_timed_startup_done = True',
    '            task._wwcombo_timed_cursor = 0',
    '            task._wwcombo_timed_base = None',
    '            task._wwcombo_timed_pending_switch = None',
    '            task._wwcombo_timed_skipped_windows = []',
    '            task._wwcombo_timed_skip_until_ms = -1',
    '        except BaseException:',
    '            task._wwcombo_timed_aborted = True',
    '            raise',
    '        finally:',
    '            for code in tuple(held):',
    '                self._wwcombo_emit("mouseup" if code.startswith("Mouse") else "keyup", code, held)',
    '            task._wwcombo_timed_running = False',
    ''
  ];
  return lines.join('\n');
}
