function mergeCatalog(generated: Record<string, string>, overrides: Record<string, string>): Record<string, string> {
  return Object.fromEntries(
    Object.entries({ ...generated, ...overrides }).filter(([, translation]) => translation.trim().length > 0)
  );
}

